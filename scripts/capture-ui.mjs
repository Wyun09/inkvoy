import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import { uiHarness, readyState, workbenchState } from '../test/ui-harness.mjs';
const output = new URL('../preview/', import.meta.url); await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.platform === 'win32' ? { channel: 'msedge' } : {}) });
try {
  const { page, context } = await uiHarness(browser);
  await page.evaluate(state => { BridgeDashboard.render(state); BridgeDashboard.setTheme('light'); }, workbenchState);
  await page.screenshot({ animations: 'disabled', path: new URL('home-light.png', output).pathname.replace(/^\/([A-Za-z]:)/, '$1') });
  await page.locator('.bottom-nav [data-navigate="tasks"]').click();
  await page.screenshot({ animations: 'disabled', path: new URL('tasks-light.png', output).pathname.replace(/^\/([A-Za-z]:)/, '$1') });
  await page.locator('[data-task="task_scene"]').click();
  await page.screenshot({ animations: 'disabled', path: new URL('task-detail.png', output).pathname.replace(/^\/([A-Za-z]:)/, '$1') });
  await page.locator('#close-sheet').click();
  await page.locator('[data-board="sessions"]').click();
  await page.screenshot({ animations: 'disabled', path: new URL('sessions-light.png', output).pathname.replace(/^\/([A-Za-z]:)/, '$1') });
  await page.locator('[data-board="tasks"]').click();
  await page.evaluate(() => BridgeDashboard.setTheme('dark'));
  await page.screenshot({ animations: 'disabled', path: new URL('tasks-dark.png', output).pathname.replace(/^\/([A-Za-z]:)/, '$1') });
  await page.evaluate(() => BridgeDashboard.setTheme('light'));
  await page.locator('.bottom-nav [data-navigate="connect"]').click();
  await page.screenshot({ animations: 'disabled', path: new URL('connect-light.png', output).pathname.replace(/^\/([A-Za-z]:)/, '$1') });
  await page.locator('.bottom-nav [data-navigate="home"]').click();
  await page.evaluate(() => BridgeDashboard.setTheme('dark'));
  await page.screenshot({ animations: 'disabled', path: new URL('home-dark.png', output).pathname.replace(/^\/([A-Za-z]:)/, '$1') });
  await page.evaluate(() => { BridgeDashboard.render({ reasoningMode: { count: 1, enabled: false, source: 'ds_toggle_component' } }); BridgeDashboard.setTheme('light'); });
  await page.locator('.health-strip [data-action="reasoning"]').click();
  await page.screenshot({ animations: 'disabled', path: new URL('reasoning-sheet.png', output).pathname.replace(/^\/([A-Za-z]:)/, '$1') });
  await page.locator('#close-sheet').click();
  await page.evaluate(() => BridgeDashboard.render({ conversations: { tracked: 1, created: 1, reused: 7 } }));
  await page.locator('[data-action="conversations"]').click();
  await page.screenshot({ animations: 'disabled', path: new URL('conversation-sheet.png', output).pathname.replace(/^\/([A-Za-z]:)/, '$1') });
  await page.locator('#close-sheet').click();
  await page.evaluate(state => { BridgeDashboard.render({ ...state, busy: false, conversations: { reused: 0, created: 0, tracked: 0 }, storage: { available: false }, taskboard: { totalRequests: 0, tasks: [], sessions: [] } }); document.querySelector('#page-home').scrollTop = 0; }, readyState);
  await page.screenshot({ animations: 'disabled', path: new URL('home-empty.png', output).pathname.replace(/^\/([A-Za-z]:)/, '$1') });
  await page.setViewportSize({ width: 320, height: 700 });
  await page.evaluate(state => BridgeDashboard.render(state), workbenchState);
  await page.locator('.bottom-nav [data-navigate="tasks"]').click();
  await page.screenshot({ animations: 'disabled', path: new URL('tasks-320.png', output).pathname.replace(/^\/([A-Za-z]:)/, '$1') });
  await context.close();
  await writeFile(new URL('README.md', output), '# UI preview\n\nThese are the actual packaged HTML/CSS UI assets rendered in desktop Edge at 390x844 with a simulated native state. They are not Android-device screenshots or proof of a real logged-in session.\n');
  console.log('Captured 11 UI previews from packaged assets with simulated state, including tasks, timelines, sessions and 320px layout.');
} finally { await browser.close(); }

